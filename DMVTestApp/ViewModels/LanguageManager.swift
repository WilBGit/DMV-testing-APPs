    private var localizations: [String: [String: String]] = [:]

    init() {
        let saved = UserDefaults.standard.string(forKey: "selectedLanguage")
        self.currentLanguage = saved ?? "en"
        loadLocalizations()
    }

    func localizedString(_ key: String) -> String {
        localizations[currentLanguage]?[key] ?? localizations["en"]?[key] ?? key
    }

    var layoutDirection: LayoutDirection {
        currentLanguage == "ar" ? .rightToLeft : .leftToRight
    }

